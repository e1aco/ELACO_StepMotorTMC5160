/**
  * @brief  CAN1 RX0 FIFO 消息挂起回调
  * @param  hcan: CAN 句柄
  * @retval 无
  * @note   校验通过后入队，命令解析在主循环进行
  */
void HAL_CAN_RxFifo0MsgPendingCallback(CAN_HandleTypeDef *hcan)
{
  CAN_RxHeaderTypeDef rx_header;
  uint8_t rx_data[8];
  uint8_t sum = 0;
  uint8_t i;

  if (HAL_CAN_GetRxMessage(hcan, CAN_RX_FIFO0, &rx_header, rx_data) != HAL_OK)
  {
    return;
  }

  if (CAN_RX_ID != rx_header.ExtId)
  {
    return;
  }

  /* 校验和: 前7字节累加取低8位 */
  for (i = 0; i < 7; i++)
  {
    sum += rx_data[i];
  }
  if (sum != rx_data[7])
  {
    return;
  }

  QUEUE_Insert(&g_queue_st, rx_data);
}

/**
  * @brief  定时器周期中断回调（HAL 全局回调）
  * @param  htim: 定时器句柄
  * @retval 无
  * @note   TIM7 周期到 → 置闭环节拍标志，业务在主循环执行
  *         ISR 中禁止 SPI/Delay 操作，避免与主循环冲突
  */
void HAL_TIM_PeriodElapsedCallback(TIM_HandleTypeDef *htim)
{
  if (htim->Instance == TIM7)
  {
    g_cl_tick_flag = 1;
  }
}
